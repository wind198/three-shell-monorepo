import { existsSync, readdirSync, readFileSync, writeFileSync, mkdirSync, watch } from 'node:fs';
import { resolve, join, relative, sep } from 'node:path';

const factoryRegex = /export\s+function\s+(create[A-Z]\w*)\s*\(/;
const safeId = /^[a-z][a-z0-9-]*\/[a-z][a-z0-9-]*$/;

function scan(directory, prefix = '') {
  if (!existsSync(directory)) return [];
  const results = [];
  for (const item of readdirSync(directory, { withFileTypes: true })) {
    const path = join(directory, item.name);
    if (item.isDirectory()) results.push(...scan(path, prefix ? prefix + '/' + item.name : item.name));
    else if (item.isFile() && item.name.endsWith('.ts') && !item.name.endsWith('.d.ts')) {
      const id = prefix + '/' + item.name.slice(0, -3);
      if (safeId.test(id)) results.push({ id, path });
    }
  }
  return results;
}

export function generateCatalog({ packageRoot }) {
  const sourceRoot = join(packageRoot, 'src/upstream');
  const metaPath = join(packageRoot, 'catalog/assets.json');
  const metadata = existsSync(metaPath) ? JSON.parse(readFileSync(metaPath, 'utf8')) : [];
  const byId = new Map(metadata.map(x => [x.id, x]));
  const entries = [];
  const issues = [];
  for (const item of scan(sourceRoot).sort((a,b) => a.id.localeCompare(b.id))) {
    const source = readFileSync(item.path, 'utf8');
    const factory = source.match(factoryRegex)?.[1];
    if (!factory) { issues.push(item.id + ': missing exported create* factory'); continue; }
    const provided = byId.get(item.id);
    const name = item.id.split('/')[1].split('-').map(x => x[0].toUpperCase() + x.slice(1)).join(' ');
    // For sources without catalog metadata, discover variant literals from a typed union.
    const variantType = source.match(/export\s+type\s+\w*Variant\s*=\s*([^;]+);/)?.[1];
    const discoveredVariants = variantType ? [...variantType.matchAll(/['"]([^'"]+)['"]/g)].map(m => m[1]) : [];
    const definition = {
      id: item.id, name: provided?.name ?? name,
      category: provided?.category ?? item.id.split('/')[0],
      placement: provided?.placement ?? 'floor',
      variants: provided?.variants ?? discoveredVariants,
      ...(provided?.dimensions ? { dimensions: provided.dimensions } : {}),
    };
    entries.push({ definition, factory });
  }
  const lines = entries.map(({definition, factory}) =>
    '  { ...' + JSON.stringify(definition) + ', factory: ' + JSON.stringify(factory) +
    ', load: () => import(' + JSON.stringify('./upstream/' + definition.id) + ') },');
  const content = [
    '/* Generated by tools/asset-discovery. Do not edit. */',
    "import type { AssetDefinition } from './types';",
    'export const assetList: readonly AssetDefinition[] = [',
    ...lines,
    '];',
    'export const assets: Readonly<Record<string, AssetDefinition>> = Object.fromEntries(assetList.map(a => [a.id, a]));',
    ''
  ].join('\n');
  return { content, entries, issues };
}

export function syncAssetCatalog({ packageRoot, dryRun = false }) {
  const { content, entries, issues } = generateCatalog({ packageRoot });
  const output = join(packageRoot, 'src/catalog.generated.ts');
  const changed = !existsSync(output) || readFileSync(output, 'utf8') !== content;
  if (changed && !dryRun) {
    mkdirSync(join(packageRoot, 'src'), { recursive: true });
    writeFileSync(output + '.tmp', content);
    // Atomic replacement prevents a transient incomplete module during Next compilation.
    const { renameSync } = requireRename();
    renameSync(output + '.tmp', output);
  }
  return { changed, count: entries.length, issues, output };
}
function requireRename() { return { renameSync: cachedRename }; }
// Imported statically: the generator also runs as an ESM module on Windows.
import { renameSync as cachedRename } from 'node:fs';

const activeWatchers = new Map();
export function withWorldAssets(nextConfig, { packageRoot = resolve(process.cwd(), '../../packages/world-assets') } = {}) {
  const packageDir = resolve(packageRoot);
  const report = syncAssetCatalog({ packageRoot: packageDir });
  if (report.issues.length) console.warn('[world-assets] Skipped invalid factories:', report.issues);
  if (process.env.NODE_ENV === 'development' && !activeWatchers.has(packageDir)) {
    const upstream = join(packageDir, 'src/upstream');
    if (existsSync(upstream)) {
      try {
        const watcher = watch(upstream, { recursive: true }, () => {
          try { syncAssetCatalog({ packageRoot: packageDir }); }
          catch (error) { console.error('[world-assets] Discovery failed', error); }
        });
        activeWatchers.set(packageDir, watcher);
      } catch (error) { console.warn('[world-assets] File watching unavailable:', error); }
    }
  }
  return nextConfig;
}
