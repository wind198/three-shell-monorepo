import { existsSync, mkdirSync, readdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { isAbsolute, join, relative, resolve, sep } from 'node:path';

function within(root, path) {
  const rel = relative(root, path);
  return rel && rel !== '..' && !rel.startsWith(`..${sep}`) && !isAbsolute(rel);
}
function scenePaths(root, scenesDir) {
  if (!scenesDir || isAbsolute(scenesDir) || scenesDir.split(/[\\/]/).includes('..')) {
    throw new Error('ThreeShell scenesDir must be a safe relative directory');
  }
  const projectRoot = resolve(root);
  const scenesRoot = resolve(projectRoot, scenesDir);
  if (!within(projectRoot, scenesRoot)) throw new Error('Invalid ThreeShell scenes directory');
  return { projectRoot, scenesRoot };
}
export function discoverScenes({ root = process.cwd(), scenesDir = 'src/scenes' } = {}) {
  const { scenesRoot } = scenePaths(root, scenesDir);
  if (!existsSync(scenesRoot)) return [];
  return readdirSync(scenesRoot, { withFileTypes: true })
    .filter(e => e.isDirectory() && /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/.test(e.name))
    .map(e => e.name)
    .filter(slug => existsSync(join(scenesRoot, slug, `${slug}.module.ts`)) && existsSync(join(scenesRoot, slug, `${slug}.scene.ts`)))
    .sort();
}
function toPascal(slug) { return slug.split('-').map(s => s[0].toUpperCase() + s.slice(1)).join(''); }
export function registrySource({ root = process.cwd(), scenesDir = 'src/scenes' } = {}) {
  const { scenesRoot } = scenePaths(root, scenesDir);
  const scenes = discoverScenes({root, scenesDir});
  const entries = scenes.map(slug => {
    const klass = toPascal(slug);
    const mount = existsSync(join(scenesRoot, slug, `${slug}.mount.ts`));
    return `  ${JSON.stringify(slug)}: async (container: HTMLDivElement, getProps: () => object) => {
` +
      `    const [mod, scene${mount ? ', mount' : ''}] = await Promise.all([
` +
      `      import('../${slug}/${slug}.module'),
` +
      `      import('../${slug}/${slug}.scene'),
` +
      (mount ? `      import('../${slug}/${slug}.mount'),
` : '') +
      `    ]);
` +
      (mount ? `    const providers = await mount.createMountProviders(container, getProps);
` :
        `    const hostToken = (scene as Record<string, unknown>)[${JSON.stringify(klass.toUpperCase() + '_HOST')}];
` +
        `    if (!hostToken) throw new Error('Scene ${slug} needs a host token or ${slug}.mount.ts');
` +
        `    const providers = [{ provide: hostToken, useValue: new BrowserAnimationHost() }];
`) +
      `    return { module: mod.${klass}SceneModule, scene: scene.${klass}Scene, providers };
` +
      `  },`;
  }).join('\n');
  const ids = scenes.map(s=>JSON.stringify(s)).join(' | ') || 'never';
  const source = `/* Generated by @three-shell/next. Do not edit. */
'use client';
` +
`import { createElement, type ComponentType } from 'react';
` +
`import { createSceneView as createBaseSceneView, BrowserAnimationHost, type GeneratedSceneViewProps } from '@three-shell/react';
` +
`const loaders = {
${entries}
};
` +
`export type SceneId = ${ids};
` +
`const views = Object.fromEntries(Object.entries(loaders).map(([id, loader]) => [id, createBaseSceneView(loader)])) as Record<SceneId, ComponentType<any>>;
` +
`/** Mount by scene name, without manually importing the scene or creating a view component. */
` +
`export function SceneView({scene, ...props}: {scene: SceneId; [key: string]: unknown} & GeneratedSceneViewProps) {
` +
`  return createElement(views[scene], props);
` +
`}
` +
`/** Optional typed factory for scene-specific props and callbacks. */
` +
`export function createSceneView<P extends object = Record<string, never>>(id: SceneId) {
` +
`  return createBaseSceneView<P>(loaders[id]);
` +
`}
`;
  return { source, scenes, output:join(scenesRoot,'.generated','registry.ts') };
}
/** Idempotent; no timestamp churn / HMR update loop on unchanged source. */
export function syncSceneRegistry(options = {}) {
  const { source, scenes, output } = registrySource(options);
  if (options.dryRun) return { output, scenes, content:source, created:false, changed:false };
  if (existsSync(output) && readFileSync(output, 'utf8') === source) return {output, scenes, content:source, created:false, changed:false};
  mkdirSync(join(output,'..'), {recursive:true});
  const temporary = `${output}.${process.pid}.tmp`;
  try {
    writeFileSync(temporary, source, 'utf8');
    renameSync(temporary, output);
  } finally {
    if (existsSync(temporary)) rmSync(temporary);
  }
  return {output, scenes, content:source, created:true, changed:true};
}
